"""Bind a verified surface-only revision before fresh photography/full audit.

Copied unchanged into each armed asset beside its other three repair helpers.
This module does not generate geometry, export models, alter images/materials,
or reissue validation/render PASS. The caller owns the actual native/GLB
invariant and corner-parity measurements and must pass its completed ledger.
"""
from __future__ import annotations

import ast
import copy
import hashlib
import json
from pathlib import Path, PurePosixPath
import re

SCHEMA = 1
LEDGER_NAME = 'surface-repair.json'
PURE_MAPPER_SHA256 = 'c987afcbac90596dbc4213885e8c16f6cb5b8fa644d90cc127fddaa38a4e78b1'
DEFAULT_HELPERS = ('gun_surface_fix.py', 'gun_surface_native.py',
                   'gun_surface_repair.py', 'gun_surface_bindings.py')
SURFACE_FILES = tuple(
    ['model/collision.glb']
    + [f'model/{palette}/{level}.glb'
       for palette in ('ochre', 'navy') for level in ('ship', 'lod1', 'lod2')]
    + [f'model/{palette}/source.blend' for palette in ('ochre', 'navy')])
METHOD = 'Explicit post-export surface-only revision; no architecture generated by this repair stage.'


def require(test, message):
    if not test:
        raise ValueError(message)


def digest(path):
    path = Path(path)
    before = path.stat()
    sha = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            sha.update(block)
    after = path.stat()
    require((before.st_size, before.st_mtime_ns) == (after.st_size, after.st_mtime_ns),
            'File changed while hashing: ' + str(path))
    return sha.hexdigest()


def safe(asset, relative, must_exist=True):
    require(isinstance(relative, str) and relative, 'Missing asset-relative path')
    rel = PurePosixPath(relative)
    require(not rel.is_absolute() and '..' not in rel.parts
            and '\\' not in relative and ':' not in relative, 'Unsafe asset path: ' + relative)
    path = (asset / relative).resolve()
    require(path.is_relative_to(asset), 'Path leaves asset: ' + relative)
    if must_exist:
        require(path.is_file(), 'Missing asset file: ' + relative)
    return path


def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def write(path, value):
    path = Path(path)
    raw = json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + '\n'
    # Atomic replacement also avoids modifying accepted hard-linked snapshots.
    temporary = path.with_name(path.name + '.surface-binding.tmp')
    temporary.write_text(raw, encoding='utf-8')
    temporary.replace(path)


def source_path(ident, filename):
    return f'potc/{ident}/{filename}'


def _is_main(node):
    test = node.test if isinstance(node, ast.If) else None
    return (isinstance(test, ast.Compare) and isinstance(test.left, ast.Name)
            and test.left.id == '__name__' and len(test.ops) == 1
            and isinstance(test.ops[0], ast.Eq) and len(test.comparators) == 1
            and isinstance(test.comparators[0], ast.Constant)
            and test.comparators[0].value == '__main__')


def _call(node, name):
    return (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)
            and isinstance(node.value.func, ast.Name) and node.value.func.id == name)


def _literal_build(node):
    if not _call(node, 'build'):
        return False
    call = node.value
    return (not call.keywords and len(call.args) == 2
            and isinstance(call.args[0], ast.BinOp) and isinstance(call.args[0].op, ast.Div)
            and isinstance(call.args[0].left, ast.Name) and call.args[0].left.id == 'HERE'
            and isinstance(call.args[0].right, ast.Constant) and call.args[0].right.value == 'spec.json'
            and isinstance(call.args[1], ast.Name) and call.args[1].id == 'HERE')


HOOK_MARKER = '# POTC_SURFACE_REPAIR_POST_BUILD'


def _plan_build_hook(original, package_module):
    """Append a separate main block; retain every original source byte.

    Family builders may call build inside a Return, try/finally or owned
    contextmanager. Their existing specialization and cleanup stay untouched.
    """
    require(package_module.isidentifier(), 'Repair package module must be a local identifier')
    tree = ast.parse(original)
    calls = [node for node in ast.walk(tree) if isinstance(node, ast.Call)
             and isinstance(node.func, ast.Name) and node.func.id == 'build']
    require(len(calls) == 1 and _literal_build(ast.Expr(value=calls[0])),
            "Builder must contain exactly one literal build(HERE / 'spec.json', HERE) anywhere in its AST")
    builders = [node for node in tree.body if isinstance(node, ast.ImportFrom)
                and node.module == 'v5_shipkit'
                and any(alias.name == 'build' and alias.asname is None for alias in node.names)]
    require(len(builders) == 1, 'Missing unchanged v5_shipkit build import')
    repair_calls = [node for node in ast.walk(tree) if isinstance(node, ast.Call)
                    and isinstance(node.func, ast.Name) and node.func.id == 'repair_package']
    repair_imports = [node for node in ast.walk(tree) if isinstance(node, ast.ImportFrom)
                      and any(alias.name == 'repair_package' for alias in node.names)]
    block = (f'{HOOK_MARKER}\n'
             'if __name__ == "__main__":\n'
             '    sys.path.insert(0, str(HERE))\n'
             f'    from {package_module} import repair_package\n'
             '    repair_package(HERE)\n')
    installed = HOOK_MARKER in original
    if installed:
        require(original.count(HOOK_MARKER) == 1 and original.endswith(block),
                'Existing repair hook differs from the approved append-only suffix')
        require(len(repair_calls) == len(repair_imports) == 1,
                'Existing wrapper has duplicate repair calls/imports')
        replacement = original
    else:
        require(not repair_calls and not repair_imports,
                'Existing unmarked repair stage requires explicit review')
        require(any(_is_main(node) for node in tree.body), 'The original builder lacks its main entry point')
        replacement = original + ('\n' if not original.endswith('\n') else '') + '\n' + block
        require(replacement.startswith(original), 'Append-only hook changed original source')
    planned_tree = ast.parse(replacement)
    require(_is_main(planned_tree.body[-1]) and
            ast.dump(planned_tree.body[-1], include_attributes=False) ==
            ast.dump(ast.parse(block).body[0], include_attributes=False),
            'Repair stage must be its own final main block')
    return replacement, {'installed': installed, 'literal_build_count': 1,
                         'literal_build_lineno': calls[0].lineno,
                         'known_build_import': True,
                         'original_main_blocks_retained': True,
                         'original_source_prefix_preserved': True,
                         'main_block_count': sum(_is_main(node) for node in tree.body),
                         'planned_main_block_count': sum(_is_main(node) for node in planned_tree.body),
                         'package_module': package_module,
                         'separate_post_build_hook': True}


def check_build_hook(asset, package_module='gun_surface_repair', require_installed=True):
    """Read-only replay/admission check; no source, report or model writes."""
    asset = Path(asset).resolve()
    path = safe(asset, 'build.py')
    original = path.read_bytes().decode('utf-8')
    replacement, facts = _plan_build_hook(original, package_module)
    return {'passed': facts['installed'] or not require_installed, **facts,
            'path': 'build.py', 'sha256': digest(path),
            'planned_sha256': hashlib.sha256(replacement.encode()).hexdigest()}


def install_build_hook(asset, package_module='gun_surface_repair'):
    """Append an idempotent separate main after all existing family typehooks."""
    path = safe(asset, 'build.py')
    original = path.read_bytes().decode('utf-8')
    replacement, facts = _plan_build_hook(original, package_module)
    if facts['installed']:
        return {'changed': False, 'path': 'build.py', 'sha256': digest(path), **facts}
    temporary = path.with_name(path.name + '.surface-binding.tmp')
    temporary.write_text(replacement, encoding='utf-8')
    temporary.replace(path)
    return {'changed': True, 'path': 'build.py', 'before_sha256': hashlib.sha256(original.encode()).hexdigest(),
            'sha256': digest(path), **facts, 'previously_installed': False, 'installed': True}


def _camera_rebindings(asset, before_files, after_files):
    records = []
    # These configurations deliberately pin the delivered model and preserve
    # geometric pose probes. Exact geometry invariance is a caller proof; this
    # step never claims that an old image was rendered from the repaired model.
    for filename in ('detail-camera-overrides.json', 'detail-camera-closeups.json'):
        path = asset / filename
        if not path.is_file():
            continue
        config = read(path)
        relative = config.get('model_path')
        require(relative in before_files and relative in after_files,
                'Camera identifies an unbound model: ' + filename)
        previous = config.get('model_sha256')
        require(previous in (before_files[relative], after_files[relative]),
                'Camera was not bound to this before/after model: ' + filename)
        before_sha = digest(path)
        config['model_sha256'] = after_files[relative]
        config['surface_revision_binding'] = {
            'ledger_path': LEDGER_NAME,
            'previous_model_sha256': before_files[relative],
            'current_model_sha256': after_files[relative],
            'scope': 'Camera pose, lens, visibility, lighting and existing geometric probes retained under the caller-proven unchanged positions/indices; actual PNGs must be rerendered and reviewed.'}
        write(path, config)
        records.append({'path': filename, 'before_sha256': before_sha, 'sha256': digest(path),
                        'previous_model_sha256': previous,
                        'current_model_sha256': after_files[relative],
                        'pose_and_lens_unchanged': True})
    return records


def _invalidate_review(asset, design):
    relative = design.get('detail_contract', {}).get('visual_review_path', 'detail-review.json')
    path = safe(asset, relative, must_exist=False)
    if not path.is_file():
        return {'path': relative, 'existed': False, 'new_review_required': True}
    review = read(path)
    old = copy.deepcopy(review)
    before_sha = digest(path)
    review['decision'] = 'PENDING'
    review['pending_reason'] = ('The delivered cannon surface attributes changed. Prior model/image bindings and findings are historical; regenerate current actual-GLB views and perform a new manual review before acceptance.')
    # Deliberately retain the old model, renderer, view SHAs and observations.
    require(all(review.get(key) == old.get(key) for key in
                ('model_path', 'model_sha256', 'renderer_sha256', 'views')),
            'Review invalidation must not rebind old photography')
    write(path, review)
    return {'path': relative, 'existed': True, 'before_sha256': before_sha, 'sha256': digest(path),
            'decision_before': old.get('decision'), 'decision_after': 'PENDING',
            'prior_model_sha256_retained': old.get('model_sha256'),
            'old_model_and_image_bindings_retained': True, 'new_review_required': True}


def bind_package(asset, ledger, before_files, helper_files=DEFAULT_HELPERS,
                 package_module='gun_surface_repair'):
    """Finalize source/camera/repair bindings after the caller's measured PASS.

    `before_files` and optional ledger.after_files cover exactly six visual GLBs,
    two packed Blends and collision.glb. No construction ledger is recomputed.
    The caller's geometry, material/image, COW and source-corner parity results
    remain intact in the supplied JSON ledger. Fresh photography/manual review
    and a full audit are still mandatory after this function returns.
    """
    asset = Path(asset).resolve()
    require(isinstance(ledger, dict) and ledger.get('schema') == 1
            and ledger.get('passed') is True, 'A completed schema1 measured repair PASS ledger is required')
    require(isinstance(before_files, dict) and set(before_files) == set(SURFACE_FILES),
            'Before SHA map must cover exactly two Blends, six visual GLBs and collision')
    require(all(isinstance(value, str) and re.fullmatch('[0-9a-f]{64}', value)
                for value in before_files.values()), 'Invalid before file SHA')
    spec_path = safe(asset, 'spec.json');design_path = safe(asset, 'design.json')
    spec, design = read(spec_path), read(design_path)
    ident = spec.get('id')
    require(ident == asset.name and design.get('id') == ident and spec.get('detail_schema') == 5,
            'Repair asset identity/detail schema mismatch')
    require(design.get('counts', {}).get('actualgun_count', 0) > 0,
            'This binding stage is only for armed assets; Tartane remains unchanged')
    helper_files = tuple(helper_files)
    require(len(helper_files) == len(set(helper_files)) and set(DEFAULT_HELPERS) <= set(helper_files),
            'All four reproducible local repair helper sources are required')
    for name in helper_files:
        require(Path(name).name == name and name.endswith('.py'), 'Expected a top-level own Python helper')
        safe(asset, name)
    require(digest(asset / 'gun_surface_bindings.py') == digest(__file__),
            'The copied binding helper differs from the executing helper')
    require(digest(asset / 'gun_surface_fix.py') == PURE_MAPPER_SHA256,
            'Pure mapper differs from independently approved c987 snapshot')
    after_files = {relative: digest(safe(asset, relative)) for relative in SURFACE_FILES}
    require(after_files['model/collision.glb'] == before_files['model/collision.glb'],
            'Collision file must remain byte-identical')
    if 'before_files' in ledger:
        require(ledger['before_files'] == before_files, 'Ledger before files differ')
    if 'after_files' in ledger:
        require(ledger['after_files'] == after_files, 'Ledger after files differ from actual repaired files')
    # Validate metadata inputs before installing the first source change.
    declared = spec.get('source_paths', [])
    require(isinstance(declared, list) and all(isinstance(value, str) for value in declared),
            'Existing source_paths must be a string list')
    for filename in ('detail-camera-overrides.json', 'detail-camera-closeups.json'):
        if (asset / filename).is_file():
            config = read(asset / filename)
            relative = config.get('model_path')
            require(relative in before_files and relative in after_files,
                    'Camera identifies an unbound model: ' + filename)
            require(config.get('model_sha256') in (before_files[relative], after_files[relative]),
                    'Camera was not bound to this before/after model: ' + filename)
    review_path = safe(asset, design.get('detail_contract', {}).get('visual_review_path', 'detail-review.json'),
                       must_exist=False)
    if review_path.is_file():
        require(isinstance(read(review_path), dict), 'Prior manual review must be a JSON object')
    preserved_reports = {relative: digest(asset / relative) for relative in
                         ('validation.json', 'export-review.json', 'detail-render.json')
                         if (asset / relative).is_file()}
    original_design = copy.deepcopy(design)
    build_hook = install_build_hook(asset, package_module)
    declared = spec.setdefault('source_paths', [])
    for filename in (*helper_files, LEDGER_NAME):
        relative = source_path(ident, filename)
        if relative not in declared:
            declared.append(relative)
    write(spec_path, spec)
    design['surface_revision'] = {
        'schema': SCHEMA, 'ledger_path': LEDGER_NAME, 'method': METHOD,
        'parameters': copy.deepcopy(ledger.get('parameters', {})),
        'source_rule': 'The canonical build runs the original construction/export pipeline, then the same explicit repair_package(HERE) stage.',
        'construction_counts_rooms_joints_materials_texture_ledgers': 'Retained; this stage does not claim a fresh architecture build.'}
    require({key: value for key, value in design.items() if key != 'surface_revision'} ==
            {key: value for key, value in original_design.items() if key != 'surface_revision'},
            'Construction ledger changed outside the explicit surface revision note')
    write(design_path, design)
    camera_bindings = _camera_rebindings(asset, before_files, after_files)
    review_invalidation = _invalidate_review(asset, design)
    require(all(digest(asset / relative) == sha for relative, sha in preserved_reports.items()),
            'Old validation/export/render evidence must remain unchanged and stale until regenerated')
    report = copy.deepcopy(ledger)
    report.update(schema=SCHEMA, method=METHOD, before_files=dict(before_files), after_files=after_files)
    own_sources = {source_path(ident, filename): digest(safe(asset, filename))
                   for filename in ('build.py', 'spec.json', 'design.json', *helper_files)}
    report['bindings'] = {
        'schema': SCHEMA, 'asset_id': ident, 'ledger_path': LEDGER_NAME,
        'binding_helper_sha256': digest(asset / 'gun_surface_bindings.py'),
        'repair_source_sha256': own_sources,
        'source_closure_scope': 'Own helper/build/spec/design files and this ledger are declared; fresh frozen audit computes the complete transitive source/inventory hashes. This is not a replacement source audit.',
        'build_hook': build_hook, 'camera_configs': camera_bindings,
        'prior_manual_review': review_invalidation,
        'old_validation_export_review_detail_render_sha256_unchanged': preserved_reports,
        'fresh_renders_manual_review_and_full_audit_required': True,
        'prohibited_acceptance_reuse': ['old validation signatures', 'old render/model SHA substitutions',
                                        'old manual PASS', '--reuse-review', '--detail-only'],
        'original_construction_ledger_retained': True,
        'collision_sha256_unchanged': after_files['model/collision.glb']}
    write(asset / LEDGER_NAME, report)
    return {'asset_id': ident, 'ledger_path': str(asset / LEDGER_NAME),
            'ledger_sha256': digest(asset / LEDGER_NAME),
            'repair_source_sha256': own_sources, 'camera_configs': camera_bindings,
            'review_decision': 'PENDING', 'fresh_renders_and_full_audit_required': True}
